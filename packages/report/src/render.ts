import type { Findings } from "./metrics.ts";

const pct = (a: number, b: number) => (b === 0 ? "n/a" : `${Math.round((100 * a) / b)}%`);

export interface ScanMeta {
  scannedAt: string;
  rpc: string;
  factory: string;
  windowDays: number;
  minProposals: number;
  daosOnFactory: number;
  errors: { dao: string; error: string }[];
}

/** The scan's numbers in words, with how each was measured. */
export function renderReport(m: ScanMeta, f: Findings): string {
  const { f1, f2, f3, f4, f5 } = f;
  return `# Sputnik DAO scan — ${m.scannedAt.slice(0, 10)}

Generated by \`pnpm --filter @nutus/report scan\`. Rerun it to reproduce; definitions are in [DEFINITIONS.md](../../packages/report/DEFINITIONS.md).

**Scope:** ${f.daos} DAOs on \`${m.factory}\` with at least ${m.minProposals} proposals in the last ${m.windowDays} days (of ${m.daosOnFactory} DAOs on the factory), ${f.proposals} proposals in that window. RPC: ${m.rpc}.${m.errors.length ? ` ${m.errors.length} DAOs couldn't be read and are excluded.` : ""}

| | Finding |
|:--|:--|
| **F1** Small payouts lapse | ${pct(f1.smallLapsed, f1.smallPayments)} of small payments lapsed (${f1.smallLapsed}/${f1.smallPayments}) vs ${pct(f1.largeLapsed, f1.largePayments)} of large ones (${f1.largeLapsed}/${f1.largePayments}). ${f1.smallLapsedZeroVotes} of the ${f1.smallLapsed} lapsed small payments got **zero votes**. Of ${f1.recipientsWithLapse} people whose small payment lapsed, **${f1.neverRepaid} were never paid by that DAO afterwards**${f1.medianDaysToRepay !== null ? `; the rest waited a median ${f1.medianDaysToRepay} days for the next approved payment` : ""}. |
| **F2** The same payment, again and again | ${f2.repeatPayments} of ${f2.approvedPayments} approved payments (${pct(f2.repeatPayments, f2.approvedPayments)}) belong to ${f2.series} repeat series (same recipient, token and amount ≥ 3 times) in ${f2.daosWithSeries} DAOs. Each one was voted on from scratch. |
| **F3** Silent seats | ${f3.silentSeats} of ${f3.seats} council seats (${pct(f3.silentSeats, f3.seats)}) cast no vote in the last 60 days, across ${f3.daosAssessed} DAOs with something to vote on. **${f3.frozenRoles} roles can no longer pass a payment** with their active members; ${f3.oneAwayRoles} more are one silent seat away. ${f3.frozenDaos} DAOs are frozen for payments outright. |
| **F4** Approved, then failed | ${f4.failed} proposals passed the vote and then failed to execute, in ${f4.daos} DAOs. By kind: ${Object.entries(f4.byCause).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(", ") || "none"}. |
| **F5** Bounties | ${f5.bountyProposals} bounty proposals in ${f5.daosUsingBounties} DAOs: Sputnik's built-in bounty flow is ${f5.bountyProposals === 0 ? "unused" : "rarely used"}. |
`;
}
